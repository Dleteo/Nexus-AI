import assert from "node:assert/strict";
import {analyzeFactoryRequest,factoryBriefMarkdown,FACTORY_ROLES,FACTORY_SKILLS} from "../lib/nexus-factory-engine.mjs";

assert.equal(analyzeFactoryRequest("short"),null,"No meaningless or unreviewable briefs");
assert.equal(analyzeFactoryRequest("x".repeat(501)),null,"Reject overlong requests");
assert.equal(analyzeFactoryRequest(null),null,"Reject non-string inputs");
const feature=analyzeFactoryRequest("Build an accessible project dashboard with mobile layout","feature");
assert.ok(feature,"Valid work item must be analyzed");
assert.equal(feature.kind,"feature");
assert.equal(feature.risk,"standard");
assert.ok(feature.skills.some(s=>s.id==="ui"),"UI skill must be selected from task evidence");
assert.equal(feature.gates.find(x=>x.id==="implementation").state,"not_run");
assert.equal(feature.gates.find(x=>x.id==="approval").state,"required");
assert.equal(feature.gates.find(x=>x.id==="handoff").state,"blocked");
assert.deepEqual(FACTORY_ROLES.map(x=>x.id),["triage","spec","build","qa","review"]);
assert.equal(FACTORY_SKILLS.some(x=>x.id==="security"),true);
assert.deepEqual(analyzeFactoryRequest("Build an accessible project dashboard with mobile layout","feature"),feature,"Intake is deterministic");
const risky=analyzeFactoryRequest("Deploy authentication and Stripe billing to production","feature");
assert.equal(risky.risk,"elevated","Sensitive work triggers more review");
assert.ok(risky.riskFlags.length>=3,"Several independent risk boundaries should be visible");
assert.ok(risky.skills.some(x=>x.id==="security"));
const bug=analyzeFactoryRequest("Fix a failing login button on the dashboard","bug");
assert.ok(bug.acceptance.some(x=>/regression test/.test(x)),"Bug reports require regression evidence");
const refactor=analyzeFactoryRequest("Refactor the response handler without changing behavior","refactor");
assert.equal(refactor.risk,"moderate");
assert.ok(refactor.acceptance.some(x=>/Preserve externally/.test(x)));
const unsupported=analyzeFactoryRequest("Review the public documentation for requirements","unknown");
assert.equal(unsupported.kind,"feature","Unsupported kinds use the constrained default");
const markdown=factoryBriefMarkdown(analyzeFactoryRequest("Review <script>alert(1)</script> in a sample page","feature"));
assert.ok(markdown.startsWith("# Nexus Factory"));
assert.ok(!markdown.includes("<script>"),"Export does not emit raw HTML tags from user input");
assert.ok(markdown.includes("No AI agent ran"),"Explicit runtime honesty is mandatory");
assert.ok(markdown.includes("A person must approve the spec"),"Human handoff cannot be skipped");
assert.equal(factoryBriefMarkdown(null),null);
console.log("PASS Nexus Factory intake, risk gates, procedures, export and runtime disclosures");
